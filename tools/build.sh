#!/usr/bin/env bash
# Deterministically rebuild all cross-agent artifacts from source files:
#   1. llms-full.txt                                      (single-file corpus for chat / RAG hosts)
#   2. bundles/short-form-script-writer-pro.zip           (plain-text Gemini Skill / universal folder bundle)
#   3. .agents/skills/<name> + bundles/antigravity/*.zip (Google Antigravity workspace/global skill)
#   4. short-form-script-writer-pro.skill                 (Claude.ai / Cowork .skill archive)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

SKILL_NAME="$(awk -F': *' '/^name:/{print $2; exit}' SKILL.md | tr -d ' "\r')"
if [ -z "$SKILL_NAME" ]; then
  echo "build: could not read 'name:' from SKILL.md" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# 1. Rebuild llms-full.txt
# ---------------------------------------------------------------------------
CORPUS_FILES=(
  "AGENTS.md"
  "SKILL.md"
  "references/combined-skills-fallback.md"
  "portable/system-prompt.md"
  "portable/gemini-gem-instructions.md"
  "portable/kimi-instructions.md"
  "portable/chatgpt-instructions.md"
  "portable/mini-prompt.md"
  "portable/kickoff-prompt.md"
)

for f in "${CORPUS_FILES[@]}"; do
  [ -f "$f" ] || { echo "build: missing $f" >&2; exit 1; }
done

TMP_CORPUS="$(mktemp)"
STAGE="$(mktemp -d)"
trap 'rm -f "$TMP_CORPUS"; rm -rf "$STAGE"' EXIT

{
  cat <<'HEADER'
# Short-Form Script Writer Pro — Full Single-File Corpus (`llms-full.txt`)

> Drop this single file into Kimi, ChatGPT, Google Gemini, Google Antigravity,
> Claude Projects, DeepSeek, Grok, Perplexity, Qwen, or any RAG / API knowledge base to enable
> the complete Short-Form Script Writer Pro workflow with zero repository setup.
>
> Core house rules across all surfaces:
> - Extract story/topic, core message, takeaway action, target length, and whether research is requested; proceed without questions when the topic is clear.
> - Size duration to concept & story complexity when unspecified (30s, 45s, 60s default for stories, 75s, 90s, 120s), keeping Hook (2-4s) and Closer (2-5s) as single sentences while expanding Story and Turn.
> - Run 30-day discourse research ONLY when requested, using findings strictly to sharpen the Hook and angle without adding unapproved research facts.
> - Strip all AI writing tells (no "not X, but Y" contrasts, staged openers, forced triads, em/en dashes, AI buzzwords, or vague attributions).
> - Output ONLY the five plain-text voiceover beats (Hook, Story, Turn, Takeaway, Closer) with zero visual/camera cues and zero intro/outro notes.
>
> Generated by tools/build.sh — do not edit by hand.

## Contents

HEADER

  for f in "${CORPUS_FILES[@]}"; do
    printf -- '- %s\n' "$f"
  done
  printf '\n'

  for f in "${CORPUS_FILES[@]}"; do
    printf '\n\n---\n\n<!-- ===== BEGIN %s ===== -->\n\n' "$f"
    cat "$f"
    printf '\n<!-- ===== END %s ===== -->\n' "$f"
  done
} > "$TMP_CORPUS"

mv "$TMP_CORPUS" llms-full.txt
printf 'build: wrote llms-full.txt (%s bytes, %s lines)\n' \
  "$(wc -c < llms-full.txt | tr -d ' ')" "$(wc -l < llms-full.txt | tr -d ' ')"

# ---------------------------------------------------------------------------
# 2. Rebuild bundles/short-form-script-writer-pro.zip (Gemini Skill & plain-text bundle)
# ---------------------------------------------------------------------------
GEMINI_BUNDLE="$STAGE/gemini/$SKILL_NAME"
mkdir -p "$GEMINI_BUNDLE/references" "$GEMINI_BUNDLE/portable"

cp SKILL.md  "$GEMINI_BUNDLE/SKILL.md"
cp AGENTS.md "$GEMINI_BUNDLE/AGENTS.md"
cp README.md "$GEMINI_BUNDLE/README.md"
cp references/combined-skills-fallback.md "$GEMINI_BUNDLE/references/"
cp portable/*.md "$GEMINI_BUNDLE/portable/"

cat > "$GEMINI_BUNDLE/READ-ME-FIRST.txt" <<'READ_ME'
SHORT-FORM SCRIPT WRITER PRO — UNIVERSAL & GEMINI SKILL BUNDLE
==============================================================

This plain-text folder works across Gemini, ChatGPT, Kimi, Claude, and coding agents:

1. GOOGLE GEMINI (Skills upload — recommended):
   - Unzip this archive first so you have the 'short-form-script-writer-pro' folder.
   - Open gemini.google.com -> Customize -> Skills -> Create -> Upload.
   - Select the unzipped 'short-form-script-writer-pro' folder and click Create.
   (Meets Gemini's upload rules: SKILL.md sits in the main folder, folder name
   matches kebab-case skill name, plain-text .md/.txt files only.)

2. CHATGPT / KIMI / GEMINI GEMS / GROK / DEEPSEEK / PERPLEXITY:
   - Open portable/README.md and copy the prompt block matching your app:
     * portable/system-prompt.md          -> Custom GPTs, ChatGPT/Claude Projects, APIs
     * portable/gemini-gem-instructions.md -> Gemini Gems
     * portable/kimi-instructions.md      -> Kimi+ Custom Assistants (kimi.ai)
     * portable/chatgpt-instructions.md   -> ChatGPT Paid Custom Instructions
     * portable/mini-prompt.md            -> ChatGPT Free Custom Instructions (<1500 chars)
     * portable/kickoff-prompt.md         -> Paste directly into any plain chat

3. CODING AGENTS (Claude Code, Codex, Cursor, Copilot, Gemini CLI, Kimi CLI, Windsurf):
   - Drop this folder into ~/.claude/skills/short-form-script-writer-pro or your workspace.
   - AGENTS.md and SKILL.md are picked up automatically.
READ_ME

find "$GEMINI_BUNDLE" -exec touch -t 202601010000 {} +
mkdir -p bundles
rm -f "bundles/$SKILL_NAME.zip"
( cd "$STAGE/gemini" && find "$SKILL_NAME" -type f | LC_ALL=C sort \
    | zip -qX -D "$ROOT/bundles/$SKILL_NAME.zip" -@ )

printf 'build: wrote bundles/%s.zip (%s bytes)\n' \
  "$SKILL_NAME" "$(wc -c < "bundles/$SKILL_NAME.zip" | tr -d ' ')"

# ---------------------------------------------------------------------------
# 3. Rebuild the Google Antigravity workspace skill and portable archive.
#    The workspace copy is auto-discovered from .agents/skills/<name>/.
# ---------------------------------------------------------------------------
ANTIGRAVITY_STAGE="$STAGE/antigravity/$SKILL_NAME"
mkdir -p "$ANTIGRAVITY_STAGE/references" "$ANTIGRAVITY_STAGE/scripts"
cp SKILL.md "$ANTIGRAVITY_STAGE/SKILL.md"
cp references/combined-skills-fallback.md "$ANTIGRAVITY_STAGE/references/"
cp scripts/validate_script.py "$ANTIGRAVITY_STAGE/scripts/"
find "$ANTIGRAVITY_STAGE" -exec touch -t 202601010000 {} +

ANTIGRAVITY_WORKSPACE="$ROOT/.agents/skills/$SKILL_NAME"
mkdir -p "$ANTIGRAVITY_WORKSPACE/references" "$ANTIGRAVITY_WORKSPACE/scripts"
cp "$ANTIGRAVITY_STAGE/SKILL.md" "$ANTIGRAVITY_WORKSPACE/SKILL.md"
cp "$ANTIGRAVITY_STAGE/references/combined-skills-fallback.md" "$ANTIGRAVITY_WORKSPACE/references/combined-skills-fallback.md"
cp "$ANTIGRAVITY_STAGE/scripts/validate_script.py" "$ANTIGRAVITY_WORKSPACE/scripts/validate_script.py"

mkdir -p "$ROOT/bundles/antigravity"
rm -f "$ROOT/bundles/antigravity/$SKILL_NAME.zip"
( cd "$STAGE/antigravity" && find "$SKILL_NAME" -type f | LC_ALL=C sort \
    | zip -qX -D "$ROOT/bundles/antigravity/$SKILL_NAME.zip" -@ )
printf 'build: wrote .agents/skills/%s/ and bundles/antigravity/%s.zip (%s bytes)\n' \
  "$SKILL_NAME" "$SKILL_NAME" "$(wc -c < "$ROOT/bundles/antigravity/$SKILL_NAME.zip" | tr -d ' ')"

# ---------------------------------------------------------------------------
# 4. Rebuild short-form-script-writer-pro.skill (Claude.ai / Cowork .skill archive)
# ---------------------------------------------------------------------------
CLAUDE_BUNDLE="$STAGE/claude/$SKILL_NAME"
mkdir -p "$CLAUDE_BUNDLE/references" "$CLAUDE_BUNDLE/scripts"

cp SKILL.md "$CLAUDE_BUNDLE/SKILL.md"
cp AGENTS.md "$CLAUDE_BUNDLE/AGENTS.md"
cp references/combined-skills-fallback.md "$CLAUDE_BUNDLE/references/"
cp scripts/validate_script.py "$CLAUDE_BUNDLE/scripts/"

find "$CLAUDE_BUNDLE" -exec touch -t 202601010000 {} +
rm -f "$SKILL_NAME.skill"
( cd "$STAGE/claude" && find "$SKILL_NAME" -type f | LC_ALL=C sort \
    | zip -qX -D "$ROOT/$SKILL_NAME.skill" -@ )

printf 'build: wrote %s.skill (%s bytes)\n' \
  "$SKILL_NAME" "$(wc -c < "$SKILL_NAME.skill" | tr -d ' ')"
